const copy = computed(() => content[locale.value]);
const themeIcon = computed(() => (isDark.value ? icons.sun : icons.moon));
const themeLabel = computed(() => (isDark.value ? 'Light mode' : 'Dark mode'));
const localeToggleLabel = computed(() => (locale.value === 'bn' ? 'EN' : 'BN'));

onMounted(() => {
    document.documentElement.classList.toggle('dark', isDark.value);
});

watch(isDark, (value) => {
    document.documentElement.classList.toggle('dark', value);
    localStorage.setItem('theme', value ? 'dark' : 'light');
}, { immediate: true });

watch(locale, (value) => {
    localStorage.setItem('locale', value);
});

const toggleTheme = () => {
    isDark.value = !isDark.value;
};

const toggleLocale = () => {
    locale.value = locale.value === 'bn' ? 'en' : 'bn';
};

export function useStorefront() {
    return {
        copy,
        categoryCollageImage,
        heroImage,
        icons,
        isDark,
        locale,
        localeToggleLabel,
        themeIcon,
        themeLabel,
        toggleLocale,
        toggleTheme,
    };
}
